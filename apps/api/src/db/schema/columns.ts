// Shared column helpers so every Drizzle table matches the SQL conventions (CLAUDE.md "Conventions").
// The SQL migrations are the source of truth; these only describe the columns to the query builder.
import { sql } from 'drizzle-orm';
import { customType, timestamp } from 'drizzle-orm/pg-core';

/**
 * BIGINT as a string. The pg driver is configured to return int8 as string (db/client.ts),
 * so ids never lose precision and are compared as strings everywhere.
 */
export const bigintString = customType<{ data: string; driverData: string }>({
  dataType: () => 'bigint',
});

/** `id BIGINT GENERATED ALWAYS AS IDENTITY`: generated by the database, never sent on insert. */
export const identityId = () =>
  bigintString('id')
    .primaryKey()
    .generatedAlwaysAs(sql`identity`);

/** company_id: defaults in SQL to core.current_company_id() (set by withTransaction). */
export const companyId = () => bigintString('company_id').notNull().default(sql`core.current_company_id()`);

/** created_at/by, updated_at/by: SQL defaults + core.touch_updated trigger fill them. */
export const auditColumns = () => ({
  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
  createdBy: bigintString('created_by').notNull().default(sql`core.current_user_id()`),
  updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
  updatedBy: bigintString('updated_by').notNull().default(sql`core.current_user_id()`),
});

export const tstz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });
